import {readFile,writeFile} from 'node:fs/promises';
import {assembleOfflineHtml,verifyOfflineHtml,removeCssImports,catAssetBootstrap} from './offline-html.mjs';
const read=p=>readFile(new URL(p,import.meta.url),'utf8');
const strip=s=>s.replace(/^import[^\n]+\n/gm,'').replace(/\bexport\s+(?=(?:const|let|function|class)\b)/g,'');
const raw=await read('./dist/vendor/three.module.min.js');
const match=raw.match(/export\{([^}]+)\};?\s*$/);
if(!match)throw new Error('Unexpected Three.js module structure');
const fields=match[1].split(',').map(part=>{const [name,alias]=part.trim().split(/\s+as\s+/);if(!/^[\w$]+$/.test(name)||alias&&!/^[\w$]+$/.test(alias))throw new Error('Invalid export');return `${alias||name}:${name}`;}).join(',');
const three=`const THREE=(()=>{${raw.slice(0,match.index)};return {${fields}};})();`;
const cats=`const CATS=(()=>{${strip(await read('./dist/cats.js'))};return {cats,findCat};})();`;
const engine=`const ENGINE=(()=>{const {findCat}=CATS;${strip(await read('./dist/engine.js'))};return {HuntGame,ARENA,BONUS,distance};})();`;
const model=`const CATMODEL=(()=>{const T=THREE;const {findCat}=CATS;${strip(await read('./dist/cat-model.js'))};return {createCat,animateCat};})();`;
const world=`const WORLD=(()=>{const T=THREE;const {createCat,animateCat}=CATMODEL;const {ARENA,BONUS}=ENGINE;const {findCat}=CATS;${strip(await read('./dist/world.js'))};return {HuntWorld};})();`;
const controls=`const CONTROLLERS=(()=>{${strip(await read('./dist/controllers.js'))};return {VirtualStick,movementVector,cameraDelta};})();`;
const runtime=`const {HuntGame,ARENA,BONUS,distance}=ENGINE;const {cats,findCat}=CATS;const {HuntWorld}=WORLD;const {VirtualStick,movementVector,cameraDelta}=CONTROLLERS;${strip(await read('./dist/game.js'))}`;
const art=(await readFile(new URL('./dist/assets/cat-trio-anime.png',import.meta.url))).toString('base64');
const script=[catAssetBootstrap(art),three,cats,engine,model,world,controls,runtime].join('\n');
if(/^import\s/m.test(script))throw new Error('Offline build still contains imports');
const css=removeCssImports(await read('./dist/style.css')).replace(/--cat-art:url\('assets\/cat-trio-anime\.png'\);?/,'');
if(/url\(["']?assets\//.test(css))throw new Error('Offline CSS contains an asset path');
const headerArt='';
const html=assembleOfflineHtml({template:await read('./dist/index.html'),css,headerArt,script});
const out=new URL('./index.html',import.meta.url);
await writeFile(out,html);
const embedded=verifyOfflineHtml(await readFile(out,'utf8'),script);
await writeFile(new URL('./bundled-check.mjs',import.meta.url),embedded);
console.log(`Standalone index.html verified (${html.length.toLocaleString()} characters)`);
